export const uiDict: Record<Language, Dict> = { en, zh };

export function t(
   lang: Language,
   key: string,
   vars?: Record<string, string | number>,
): string {
   let s = uiDict[lang][key] ?? uiDict.en[key] ?? key;
   if (vars) {
      for (const [k, v] of Object.entries(vars))
         s = s.replaceAll("{" + k + "}", String(v));
   }
   return s;
}
